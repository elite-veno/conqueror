"""Rasterize world-atlas land TopoJSON onto the game's hex grid.

Usage: python3 tools/build_map.py land-50m.json > js/mapdata.js
(land-50m.json from https://cdn.jsdelivr.net/npm/world-atlas@2.0.2/land-50m.json)
"""
import json, sys, bisect

COLS = 100
DLON = 360.0 / COLS
DLAT = DLON * 0.866
LAT_TOP = 80.0
LAT_BOTTOM = -56.0
ROWS = int((LAT_TOP - LAT_BOTTOM) / DLAT)
SUB = 5          # samples per cell axis
THRESHOLD = 0.22  # land coverage needed to count as a land tile

topo = json.load(open(sys.argv[1]))
sx, sy = topo["transform"]["scale"]
tx, ty = topo["transform"]["translate"]

arcs = []
for arc in topo["arcs"]:
    x = y = 0
    pts = []
    for dx, dy in arc:
        x += dx; y += dy
        pts.append((x * sx + tx, y * sy + ty))
    arcs.append(pts)

def ring(idx_list):
    pts = []
    for i in idx_list:
        a = arcs[i] if i >= 0 else arcs[~i][::-1]
        pts.extend(a if not pts else a[1:])
    return pts

rings = []
def add_geom(g):
    if g["type"] == "Polygon":
        for r in g["arcs"]: rings.append(ring(r))
    elif g["type"] == "MultiPolygon":
        for p in g["arcs"]:
            for r in p: rings.append(ring(r))
    elif g["type"] == "GeometryCollection":
        for gg in g["geometries"]: add_geom(gg)

for obj in topo["objects"].values():
    add_geom(obj)

edges = []
for r in rings:
    for i in range(len(r) - 1):
        edges.append((r[i], r[i + 1]))

def crossings(lat):
    xs = []
    for (x1, y1), (x2, y2) in edges:
        if (y1 > lat) != (y2 > lat):
            xs.append(x1 + (lat - y1) * (x2 - x1) / (y2 - y1))
    xs.sort()
    return xs

def inside(xs, lon):
    return bisect.bisect_left(xs, lon) % 2 == 1

grid = []
for r in range(ROWS):
    lat0 = LAT_TOP - r * DLAT
    rows_x = [crossings(lat0 - (j + 0.5) * DLAT / SUB) for j in range(SUB)]
    line = []
    for c in range(COLS):
        lon0 = -180 + (c + (0.5 if r % 2 else 0)) * DLON
        hit = 0
        for xs in rows_x:
            for i in range(SUB):
                lon = lon0 + (i + 0.5) * DLON / SUB
                if lon > 180: lon -= 360
                if inside(xs, lon): hit += 1
        line.append("#" if hit / (SUB * SUB) >= THRESHOLD else ".")
    grid.append("".join(line))

print("// Generated by tools/build_map.py — do not edit by hand.")
print("window.MAPDATA = " + json.dumps({
    "cols": COLS, "rows": ROWS, "dlon": DLON, "dlat": DLAT, "latTop": LAT_TOP,
    "grid": grid}, indent=0) + ";")
